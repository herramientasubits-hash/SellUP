/** Macro de un Gran Contribuyente por su RUC, o `null`. */
export function resolveNiLargeTaxpayerMacro(ruc: string | null | undefined): MacroIndustryKey | null {
  if (typeof ruc !== 'string') return null;
  return NI_LARGE_TAXPAYER_MACRO[ruc.trim().toUpperCase()] ?? null;
}

/** ¿Tiene esta macro algún Gran Contribuyente clasificado? */
export function macroHasNiLargeTaxpayerCoverage(macroIndustryKey: string | null | undefined): boolean {
  if (typeof macroIndustryKey !== 'string') return false;
  return Object.values(NI_LARGE_TAXPAYER_MACRO).includes(macroIndustryKey as MacroIndustryKey);
}
