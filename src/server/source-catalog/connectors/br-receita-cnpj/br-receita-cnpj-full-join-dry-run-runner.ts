/**
 * BR Receita CNPJ — FULL JOIN dry-run runner scaffold (BR-SOURCE-11A / 11C Option B).
 *
 * The first technical runner for the Receita CNPJ full join, implemented as a LOCAL
 * NO-WRITE / NO-RUNTIME scaffold. It composes the three BR-SOURCE-11A safety modules
 * — the no-write guard, the output sanitizer, and the failure-cleanup model — into a
 * single entry point that produces an AGGREGATE, sanitized report.
 *
 * ── Why this runner cannot execute the real dataset ─────────────────────────────
 * None of the eight approval gates is approved (legal/privacy, temporary storage
 * envelope, field allowlist, identity grain, output sanitization, failure cleanup,
 * operator runbook, no-write/no-runtime). So:
 *
 *   - `synthetic_fixture_only` (the DEFAULT) scores an injected or built-in SYNTHETIC
 *     fixture with no file I/O at all.
 *
 *   - `local_manifest_dry_run` is authorized under exactly TWO narrow carve-outs, each
 *     selected by its own declared manifest TRUST and gated by its own owner flag:
 *
 *       · BR-SOURCE-11C **Option B** — `synthetic_temp_manifest_only`: a SYNTHETIC TEMP
 *         MANIFEST generated by a test or by the controlled synthetic-temp CLI, plus
 *         synthetic headerless CSVs, read under four bounded caps.
 *
 *       · BR-SOURCE-11D-META-IMPL — `real_manifest_metadata_only`: ONE real local
 *         manifest opened as a CONTROL DOCUMENT and parsed for schema-level metadata.
 *         **No file it references is ever opened or stat-ed**, and no row is read.
 *
 *     Any other trust — including a real manifest offered for EXECUTION — fails closed
 *     with `local_manifest_execution_not_authorized`. Reading a real Receita data file
 *     remains exactly what GATE-1 (legal/privacy) and GATE-2 (temporary storage
 *     envelope) would have to authorize, and neither is approved.
 *
 * ── Both carve-outs are NARROW, and neither substitutes for the other ───────────
 * The synthetic-temp branch proceeds only when EVERY one of these holds:
 *   `allowLocalManifest`, `manifestTrust === 'synthetic_temp_manifest_only'`,
 *   `optionBCarveoutAuthorized`, `strict`, `productionWrites === false`, an explicit
 *   `outputSanitizationVersion === 'not_approved'`, all four bounded caps present and
 *   within their Option B maxima, and an injected local-manifest reader.
 *
 * The metadata-only branch proceeds only when EVERY one of these holds:
 *   `allowLocalManifest`, `manifestTrust === 'real_manifest_metadata_only'`,
 *   `realManifestMetadataOnlyOptionBAuthorized`, `strict`, `productionWrites === false`,
 *   an explicit `outputSanitizationVersion === 'not_approved'`, both metadata caps
 *   (`maxManifestBytes`, `maxDeclaredFiles`) present and within their maxima, and an
 *   injected metadata reader.
 *
 * The owner phrases are separate, single-scope, and non-transferable, so the FLAGS are
 * separate too: `optionBCarveoutAuthorized` buys nothing on the metadata path, and
 * `realManifestMetadataOnlyOptionBAuthorized` buys nothing on the synthetic path.
 * Anything missing or out of bounds fails closed with a value-free error code.
 *
 * ── BR-SOURCE-11E: which manifest DOCUMENT may be named ─────────────────────────
 * A third flag, `realManifestMetadataOnlyExecutionAuthorized`, records that this run may
 * name the OPERATOR'S OWN prepared manifest rather than a synthetic one. It is a
 * WHICH-DOCUMENT authorization and nothing more: it relaxes no cap, opens no referenced
 * file, reads no row, computes no join, and does not satisfy the metadata gate above.
 *
 * The runner resolves no paths, so it cannot enforce the waiver — the reader does. What the
 * runner enforces is that the two declarations AGREE: a scan reporting
 * `operatorPreparedManifestAuthorized: true` on a run that did not declare the execution
 * authorization is refused with `real_manifest_metadata_execution_not_authorized`, and
 * carries no metadata block.
 *
 * The runner itself stays PURE: it never imports `node:fs` and never opens a file.
 * Reading is delegated to INJECTED reader ports — implemented by
 * `br-receita-cnpj-synthetic-temp-manifest.ts` (which owns the temp directory it created
 * itself and nothing else) and by `br-receita-cnpj-real-manifest-metadata-reader.ts`
 * (which resolves exactly one path, the manifest, and has no code path that opens a
 * second one).
 *
 * ── The runner NEVER ────────────────────────────────────────────────────────────
 *   - downloads, unzips, imports, or processes the full dataset.
 *   - opens a manifest, a CSV, a ZIP, or any file (no filesystem import at all).
 *   - opens a file a manifest references, or reads a real Receita data file, under any
 *     flag — including under the metadata-only carve-out.
 *   - reads, samples, counts, or hashes a row of real data under any flag.
 *   - opens a Supabase client, reads env vars, or writes to any database.
 *   - integrates runtime, Agent 1, providers, HubSpot, or Slack.
 *   - constructs a `record_identity_key` or a `normalized_tax_id`.
 *   - returns a row, a cell value, a full CNPJ, a CNPJ básico, a CPF, a legal name, a
 *     trade name, an email, a phone, an address, a join key, a filesystem path, or a
 *     hash of any of them.
 *   - approves a gate, or declares Brazil ready for import, runtime, or Agent 1.
 *
 * Synthetic fixture rows carry OPAQUE structural refs (never dataset-shaped) that are
 * used for in-memory association only and are never counted into, or emitted by, the
 * report.
 */

