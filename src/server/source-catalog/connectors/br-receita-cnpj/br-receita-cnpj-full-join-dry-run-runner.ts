// ─── Local manifest reader port (Option B) ────────────────────────────────────

/**
 * What the reader is allowed to ask for. Every cap is passed IN, so the reader
 * enforces the same bounds at read time that the runner enforces at gate time — a
 * bounded read is not a courtesy the reader may skip.
 */
export interface BrazilReceitaFullJoinLocalManifestReadRequest {
  readonly maxBytesPerFile: number;
  readonly maxCompanyRows: number;
  readonly maxEstablishmentRows: number;
  readonly maxCompanyScanRows: number;
}

/**
 * What the reader returns: STRUCTURAL scan metadata plus a synthetic fixture in the
 * runner's own shape. Deliberately no path, no filename, no raw line, and no cell —
 * the reader translates its workspace into aggregate-scoreable structure, so the
 * runner can stay pure and can never be handed dataset content to leak.
 *
 * The fields are typed loosely (`string`) on purpose: the reader sits at a trust
 * boundary, so the runner re-validates the trust level, the layout mode, and every
 * family name against its own allowlists rather than believing the declaration.
 */
export interface BrazilReceitaFullJoinLocalManifestScan {
  readonly manifestTrust: string;
  readonly layoutMode: string;
  /** Family labels scanned (`empresas`, `estabelecimentos`, …). Validated, then counted. */
  readonly familiesScanned: readonly string[];
  readonly filesScanned: number;
  /** True when the bounded per-file read ceiling was enforced during the read. */
  readonly bytesCapApplied: boolean;
  /** True when a file was LARGER than the per-file ceiling — a fail-closed condition. */
  readonly bytesCapExceeded: boolean;
  readonly fixture: BrazilReceitaFullJoinSyntheticFixture;
}

/** The injected port. The runner calls it at most ONCE per run, inside a try/catch. */
export type BrazilReceitaFullJoinLocalManifestReader = (
  request: BrazilReceitaFullJoinLocalManifestReadRequest,
) => BrazilReceitaFullJoinLocalManifestScan;

