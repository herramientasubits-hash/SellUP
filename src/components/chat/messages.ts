export type ChatMessageKey = keyof typeof MESSAGES;

/** El texto de una clave, con sus `{variables}` sustituidas. */
export function t(key: ChatMessageKey, vars?: Record<string, string | number>): string {
  const template: string = MESSAGES[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
